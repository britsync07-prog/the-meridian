const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, '..', '..');
const FIXTURES_DIR = path.resolve(REPO_ROOT, 'tests', 'fixtures', 'feeds');

/**
 * Normalization entrypoint used by both runner and dual-run parity tests (ING-02).
 */
export function normalizeFeedForRunner(
  xmlText: string,
  source: SourceRegistryEntry,
  snapshotTimestamp: string,
  nowMs: number = Date.now(),
): RawItem[] {
  return normalizeFeed(xmlText, source, snapshotTimestamp, nowMs);
}

/**
 * Finds the local D1 SQLite file generated by wrangler miniflare.
 */
function findLocalSqlitePath(): string | null {
  const candidates = [
    path.join(REPO_ROOT, 'apps', 'worker', '.wrangler', 'state', 'v3', 'd1', 'miniflare-D1DatabaseObject'),
    path.join(REPO_ROOT, '.wrangler', 'state', 'v3', 'd1', 'miniflare-D1DatabaseObject'),
  ];

  for (const dir of candidates) {
    if (existsSync(dir)) {
      const files = readdirSync(dir);
      const dbFile = files.find((f) => f.endsWith('.sqlite') && f !== 'metadata.sqlite');
      if (dbFile) {
        return path.join(dir, dbFile);
      }
    }
  }

  return null;
}

/**
 * Minimal D1Database adapter wrapping node:sqlite DatabaseSync without database query strings.
 */
function createSqliteD1Binding(sqliteDb: DatabaseSync): any {
  return {
    prepare(statementString: string) {
      const statement = (boundParams: any[] = []) => ({
        bind(...args: any[]) {
          return statement(args);
        },
        async all<T = unknown>() {
          const statement = sqliteDb.prepare(statementString);
          const results = statement.all(...boundParams) as T[];
          return { results, success: true, meta: { changes: 0 } };
        },
        async first<T = unknown>(col?: string) {
          const statement = sqliteDb.prepare(statementString);
          const row = statement.get(...boundParams) as any;
          if (!row) return null;
          if (col) return row[col] ?? null;
          return row as T;
        },
        async run() {
          const statement = sqliteDb.prepare(statementString);
          const info = statement.run(...boundParams);
          return { success: true, meta: { changes: Number(info.changes) } };
        },
      });
      return statement();
    },
    async batch(statements: any[]) {
      const results = [];
      for (const statement of statements) {
        const res = await statement.run();
        results.push(res);
      }
      return results;
    },
    async exec(rawCommands: string) {
      sqliteDb.exec(rawCommands);
      return { count: 0, duration: 0 };
    },
    dump: async () => new ArrayBuffer(0),
  };
}

const EDITION_COUNTRY_MAP: Record<string, { countryCode: string; language?: string }> = {
  uk: { countryCode: 'GB' },
  us: { countryCode: 'US' },
  au: { countryCode: 'AU' },
  ca: { countryCode: 'CA' },
  ie: { countryCode: 'IE' },
  nz: { countryCode: 'NZ' },
  in: { countryCode: 'IN', language: 'en' },
  'in-hi': { countryCode: 'IN', language: 'hi' },
};

export interface IngestRunOptions {
  fixtures?: boolean;
  edition?: string;
  live?: boolean;
  customSources?: readonly SourceRegistryEntry[];
  capturedXmlBySource?: ReadonlyMap<string, string>;
  repo?: Repository;
  nowMs?: number;
  includeImages?: boolean;
}

export interface IngestSummary {
  feedsProcessed: number;
  itemsNormalized: number;
  storiesAdded: number;
  errorsCount: number;
}

/**
 * Runs the local ingest pipeline.
 */
export async function runLocalIngest(options: IngestRunOptions = {}): Promise<IngestSummary> {
  // When replaying fixed offline fixtures, anchor default nowMs to fixture timestamp date
  const nowMs = options.nowMs ?? (options.fixtures || !options.live ? Date.parse('2026-10-21T12:00:00Z') : Date.now());
  const snapshotIso = new Date(nowMs).toISOString();

  let repository = options.repo;
  if (!repository) {
    const dbPath = findLocalSqlitePath();
    if (!dbPath) {
      throw new Error(
        'Could not find local D1 SQLite database in .wrangler state. Please run `npm run db:verify:local` first to initialize.',
      );
    }
    const sqliteDb = new DatabaseSync(dbPath);
    const d1Binding = createSqliteD1Binding(sqliteDb);
    const env: MeridianEnv = {
      DB: d1Binding,
      R2: {} as MeridianEnv['R2'],
      KV: {} as MeridianEnv['KV'],
    };
    repository = createRepository(env);
  }

  // Ensure sources are registered in DB
  await repository.syncSources(SOURCES);
  const activeDbSources = await repository.listActiveSources();
  const sourceIdBySlug = new Map<string, number>();
  for (const src of activeDbSources) {
    sourceIdBySlug.set(src.slug, src.id);
  }

  // Filter sources
  let targets = [...(options.customSources ?? SOURCES.filter((s) => s.isActive))];
  if (options.edition) {
    const ed = options.edition.toLowerCase();
    const mapped = EDITION_COUNTRY_MAP[ed];
    if (mapped) {
      targets = targets.filter((s) => {
        if (s.countryCode !== mapped.countryCode) return false;
        if (mapped.language && s.language !== mapped.language) return false;
        return true;
      });
    } else {
      targets = targets.filter((s) => s.countryCode.toLowerCase() === ed);
    }
  }
  if (options.capturedXmlBySource) {
    targets = targets.filter((source) => options.capturedXmlBySource!.has(source.slug));
  }

  let feedsProcessed = 0;
  let itemsNormalized = 0;
  let storiesAdded = 0;
  let errorsCount = 0;

  for (const source of targets) {
    try {
      let xmlText = '';

      if (options.capturedXmlBySource) {
        xmlText = options.capturedXmlBySource.get(source.slug) ?? '';
        if (!xmlText) throw new Error('Captured feed was empty');
      } else if (options.live) {
        const resp = await fetchWithTimeout(
          source.feedUrl,
          { 'User-Agent': USER_AGENT },
          DEFAULT_FETCH_TIMEOUT_MS,
        );
        if (!resp.ok) {
          throw new Error(`HTTP error ${resp.status}`);
        }
        xmlText = await resp.text();
      } else {
        // Replay fixtures based on language and format
        let fixtureFile = 'rss-standard.xml';
        if (source.language === 'hi') {
          fixtureFile = 'hindi-standard.xml';
        } else if (source.feedUrl.includes('.atom')) {
          fixtureFile = 'atom-standard.xml';
        }

        const fixturePath = path.join(FIXTURES_DIR, fixtureFile);
        if (existsSync(fixturePath)) {
          xmlText = readFileSync(fixturePath, 'utf8');
        } else {
          continue;
        }
      }

      feedsProcessed++;
      const rawNormalizedItems = normalizeFeedForRunner(xmlText, source, snapshotIso, nowMs);
      const normalizedItems = rawNormalizedItems.slice(0, 20);
      itemsNormalized += normalizedItems.length;

      const dbSourceId = sourceIdBySlug.get(source.slug) ?? 1;
      const storyRows: RawStoryInsert[] = normalizedItems.map((item) => ({
        sourceId: dbSourceId,
        externalGuid: item.externalGuid,
        headline: item.title,
        excerpt: item.description || null,
        url: item.canonicalUrl,
        slug: item.externalGuid.replace(/[^a-z0-9_-]/gi, '-').toLowerCase().slice(0, 80),
        language: source.language,
        publishedAt: item.publishedAt,
        fetchedAt: snapshotIso,
        countryCode: source.countryCode,
        imageUrl: item.imageUrl,
        imageCredit: item.imageCredit,
        // The source URL hash is the pre-fetch dedupe key; CI replaces it with image variants.
        imageContentHash: item.imageUrl ? createHash('sha256').update(item.imageUrl).digest('hex') : null,
      }));

      const added = await repository.batchInsertStories(storyRows, { includeImages: options.includeImages });
      storiesAdded += added;
    } catch (err) {
      errorsCount++;
      console.error(`Error processing feed ${source.slug}:`, err instanceof Error ? err.message : String(err));
    }
  }

  const summary: IngestSummary = {
    feedsProcessed,
    itemsNormalized,
    storiesAdded,
    errorsCount,
  };

  console.log('Ingest Summary:');
  console.log(`- Feeds processed: ${summary.feedsProcessed}`);
  console.log(`- Items normalized: ${summary.itemsNormalized}`);
  console.log(`- Stories added: ${summary.storiesAdded}`);
  console.log(`- Errors encountered: ${summary.errorsCount}`);

  return summary;
}

// CLI execution check
const isCli = process.argv[1]?.includes('run-local');
if (isCli) {
  const args = process.argv.slice(2);
  const isLive = args.includes('--live');
  const isFixtures = args.includes('--fixtures') || !isLive;
  const editionIndex = args.indexOf('--edition');
  const edition = editionIndex !== -1 && args[editionIndex + 1] ? args[editionIndex + 1] : undefined;

  runLocalIngest({ fixtures: isFixtures, live: isLive, edition })
    .then(() => process.exit(0))
    .catch((err) => {
      console.error('Local ingest failed:', err);
      process.exit(1);
    });
}
