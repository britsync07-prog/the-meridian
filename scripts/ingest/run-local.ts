/**
 * Local CLI ingest runner (D-26, D-28, D-30, OPS-14).
 * Replays offline fixtures or fetches active feeds, normalizes canonical items,
 * and records unclustered stories into local D1 via repository.
 *
 * Repository purity rule: All datastore operations must go through repository.ts.
 * Zero database query strings or keywords may exist in this file.
 */

