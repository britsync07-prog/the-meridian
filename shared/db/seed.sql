-- ============================================================================
-- seed.sql — the reference rows the pipeline needs before it can run.
--
-- Applied with:  npx wrangler d1 execute meridian --local --file shared/db/seed.sql
--
-- Every statement is `INSERT OR IGNORE`, so the seed is safe to re-run: it is
-- applied on every local build and every CI build, and re-running it changes
-- nothing that a curator has already edited.
--
-- WHAT IS HERE
--   * 8 editions — the seven English editions plus the Hindi edition.
--   * 8 sections — the broadsheet's eight desks.
--   * The edition-sections join — generated by a cross join, never written
--     out, so the 64 rows cannot drift from 8 x 8.
--   * A 30-outlet starter source registry across the seven countries: the
--     Track E taxonomy contribution the roadmap asks for in Phase 1.
--
-- TERMS OF USE — READ THIS BEFORE FETCHING ANYTHING
--   Every seeded source carries `terms_status = 'unverified'`. That is a hard
--   gate, not a default to be tidied up later: Phase 2 must check a
--   publisher's terms and set `terms_status = 'verified'` with a
--   `terms_verified_at` date before its feed is fetched for the first time.
--   `scripts/db/verify-local.mjs` fails if any seeded row is not unverified.
--
-- FEED URLS
--   The `feed_url` values below are the publishers' published RSS endpoints as
--   known at the time of writing. They are recorded as REGISTRY ENTRIES ONLY.
--   Phase 2 verifies each one's availability, freshness and terms of use
--   before any of them is fetched, and corrects or disables the ones that
--   fail. A URL that turns out to be wrong is a registry correction, not a
--   schema change.
-- ============================================================================

