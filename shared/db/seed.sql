-- ──────────────────────── Edition-sections join ─────────────────────────────
-- Every edition carries every section. Written as a cross join so the row
-- count is 8 x 8 by construction and can never drift.

INSERT OR IGNORE INTO edition_sections (edition_id, section_id, sort_order)
SELECT e.id, s.id, s.sort_order FROM editions e CROSS JOIN sections s;

